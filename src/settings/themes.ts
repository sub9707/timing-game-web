import { DEFAULT_GRADIENT, evenStops, linear, radial } from '../design/gradient';
import type { BackgroundSetting, DesignSetting, Fill, Gradient, GradientStop, TextFx, TextFxTarget, ThemeId } from '../types';

export interface ThemePreset {
  id: ThemeId;
  name: string;
  accent: string;
  text: string;
  bg: BackgroundSetting;
  design: DesignSetting;
}

const bg = (partial: Partial<BackgroundSetting> & Pick<BackgroundSetting, 'mode'>): BackgroundSetting => ({
  solid: '#0b0b10',
  gradient: linear(['#0b0b10', '#1c1c28'], 135),
  imageDim: 45,
  imageBlur: 0,
  chroma: '#00b140',
  ...partial,
});

/** 글자 효과 없음 (테마 기본 자간·행간 사용) */
export const NO_TEXT_FX: TextFx = { tracking: null, lineHeight: null, stroke: 0, strokeColor: '#000000', shadow: 0, shadowOffset: 0, shadowColor: '#000000aa' };
export const defaultTextFx = (): Record<TextFxTarget, TextFx> => ({
  title: { ...NO_TEXT_FX },
  sub: { ...NO_TEXT_FX },
  digits: { ...NO_TEXT_FX },
  result: { ...NO_TEXT_FX },
});

export const solid = (color: string): Fill => ({ ...DEFAULT_GRADIENT, stops: evenStops([color, color]), mode: 'solid', color });
export const gradient = (stops: string[], angle = 180, extra?: Partial<Gradient>): Fill => ({
  ...linear(stops, angle, extra),
  mode: 'gradient',
  color: stops[0],
});

/** 정지점 위치를 직접 지정 [색, 위치%] */
const at = (...pairs: [string, number][]): GradientStop[] => pairs.map(([color, pos]) => ({ color, pos }));

